#!/usr/bin/env python3
"""
Exact centered product-set verifier for the Erdős--Straus u-method.

For u = 4x - n and M = n*x, when gcd(M,u)=1 the u-method succeeds iff
there exist signed exponents c_p with -v_p(M) <= c_p <= v_p(M) such that

    product(p**c_p) == -1 (mod u).

Equivalently, -1 lies in the bounded centered product set generated by the
prime-power factors of M.

This script cross-checks that criterion against the exact direct divisor-pair
criterion. It intentionally does not use the old {-x*n^j} shortcut.
"""

from __future__ import annotations

import argparse
from math import gcd
from collections import Counter
from sympy import factorint, primerange


def is_hard_case(n: int) -> bool:
    if n % 12 != 1 or n % 5 == 0:
        return False
    b3 = n * (n + 3) // 4
    while b3 % 2 == 0:
        b3 //= 2
    return all(p % 3 == 1 for p in factorint(b3))


def centered_product_set(M: int, u: int) -> set[int]:
    """Return S_u(M) = prod_p {p^c : -a_p <= c <= a_p} mod u.

    Requires gcd(M,u)=1.
    """
    if gcd(M, u) != 1:
        raise ValueError("centered criterion requires gcd(M,u)=1")

    residues = {1 % u}
    for p, a in factorint(M).items():
        p_mod = p % u
        inv_p = pow(p_mod, -1, u)

        local = {1}
        v = 1
        for _ in range(a):
            v = (v * p_mod) % u
            local.add(v)

        v = 1
        for _ in range(a):
            v = (v * inv_p) % u
            local.add(v)

        residues = {(r * s) % u for r in residues for s in local}

    return residues


def centered_success(n: int, u: int) -> bool | None:
    if (n + u) % 4 != 0:
        return False
    x = (n + u) // 4
    if x <= 0:
        return False
    M = n * x
    if gcd(M, u) != 1:
        return None
    return ((-1) % u) in centered_product_set(M, u)


def divisor_residue_set(M: int, u: int) -> set[int]:
    """Residues modulo u represented by actual divisors of M^2."""
    residues = {1 % u}
    for p, a in factorint(M).items():
        local = {pow(p, e, u) for e in range(2 * a + 1)}
        residues = {(r * s) % u for r in residues for s in local}
    return residues


def direct_success(n: int, u: int) -> bool | None:
    """Exact direct criterion in the unit case.

    For gcd(M,u)=1, it is enough to find one divisor d|M^2 with d == -M mod u;
    the complementary divisor then has the same residue automatically.

    Returns None when gcd(M,u)!=1 so callers know the centered equivalence is
    not being asserted in that case.
    """
    if (n + u) % 4 != 0:
        return False
    x = (n + u) // 4
    if x <= 0:
        return False
    M = n * x
    if gcd(M, u) != 1:
        return None
    return ((-M) % u) in divisor_residue_set(M, u)


def first_working_u_centered(n: int, u_max: int = 300) -> tuple[int, int, int] | None:
    """Return (u,x,|S|) for the first centered success with gcd(nx,u)=1."""
    for u in range(3, u_max + 1, 4):
        if (n + u) % 4 != 0:
            continue
        x = (n + u) // 4
        M = n * x
        if gcd(M, u) != 1:
            continue
        S = centered_product_set(M, u)
        if (-1) % u in S:
            return u, x, len(S)
    return None


def cross_check(limit: int, u_max: int) -> dict:
    pairs = 0
    mismatches = []
    hard_cases = 0
    failures = []
    dist = Counter()
    residue120 = Counter()

    for n in primerange(13, limit + 1):
        if not is_hard_case(n):
            continue
        hard_cases += 1

        first = first_working_u_centered(n, u_max)
        if first is None:
            failures.append(n)
        else:
            u, x, ssize = first
            dist[u] += 1
            residue120[n % 120] += 1

        for u in range(3, u_max + 1, 4):
            if (n + u) % 4 != 0:
                continue
            x = (n + u) // 4
            M = n * x
            if gcd(M, u) != 1:
                continue
            pairs += 1
            a = centered_success(n, u)
            b = direct_success(n, u)
            if a != b:
                mismatches.append((n, u, a, b))
                if len(mismatches) >= 20:
                    break
        if len(mismatches) >= 20:
            break

    return {
        "limit": limit,
        "u_max": u_max,
        "hard_cases": hard_cases,
        "pairs_cross_checked": pairs,
        "mismatch_count": len(mismatches),
        "mismatches": mismatches,
        "first_u_failures": failures,
        "first_u_distribution": dict(sorted(dist.items())),
        "hard_case_residues_mod_120": dict(sorted(residue120.items())),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=100_000)
    parser.add_argument("--u-max", type=int, default=79)
    args = parser.parse_args()

    result = cross_check(args.limit, args.u_max)
    for k, v in result.items():
        print(f"{k}: {v}")

    if result["mismatch_count"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
