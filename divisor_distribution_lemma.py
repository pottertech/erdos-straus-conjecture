def divisor_coverage_mod_u(x_factors, u):
    """
    Given factorization of x, compute the set of residues mod u
    achieved by divisors of x².
    
    x² has factorization {p: 2*e for p, e in x_factors.items()}.
    Divisors of x² mod u = all products of p^(0..2e) mod u.
    """
    if not x_factors:
        return {1 % u}
    
    divs = {1 % u}
    for p, e in x_factors.items():
        p_mod = p % u
        if p_mod == 0:
            continue
        new_divs = set()
        pe = 1
        for exp in range(2*e + 1):
            for d in divs:
                new_divs.add((d * pe) % u)
            pe = (pe * p_mod) % u
        divs = new_divs
    return divs

def three_targets(n, u):
    """Compute the three target residues mod u."""
    x = (n + u) // 4
    x_mod = x % u
    n_mod = n % u
    
    # Targets: -x * n^(1-a) mod u for a in {0, 1, 2}
    # a=0: -xn mod u
    # a=1: -x mod u  
    # a=2: -x * n^(-1) mod u
    
    n_inv = pow(n_mod, -1, u) if n_mod % u != 0 else None
    
    targets = {
        (-x_mod * n_mod) % u,  # a=0
        (-x_mod) % u,           # a=1
        (-x_mod * n_inv) % u if n_inv else None,  # a=2
    }
    targets.discard(None)
    return targets

def min_omega_for_guarantee(u, n_samples=1000):
    """
    For a given u, determine the minimum ω(x) such that the u-method
    is guaranteed to work (i.e., divisors of x² ALWAYS hit a target).
    
    Strategy: For each ω from 1 to 10, generate random x with ω(x) = ω
    prime factors, compute coverage mod u, and check if any miss the targets.
    
    Since we can't enumerate all x, we use a structural argument:
    - Each prime factor of x generates a cyclic subgroup of (Z/uZ)*
    - The divisor set is the product of these cyclic subgroups (with bounded exponents)
    - Coverage depends on the subgroup structure
    """
    if not isprime(u):
        return None  # Only analyze prime u
    
    # (Z/uZ)* is cyclic of order u-1
    # Each prime p | x generates elements {p^0, p^1, ..., p^(2e)} mod u
    # This is a subset of the cyclic subgroup generated by p mod u
    
    # For ω(x) = k with exponents e_i ≥ 1:
    # Divisors of x² = product of {p_i^0, ..., p_i^(2*e_i)} mod u
    # |divisors| ≤ product of (2*e_i + 1)
    
    # For the coverage to be guaranteed, we need the product set to
    # contain at least one of the 3 targets for ANY choice of primes.
    
    # Worst case: all primes are in the same coset of a subgroup
    # that doesn't contain any target.
    
    # The key structural fact: if the primes generate DISTINCT subgroups
    # whose product is all of (Z/uZ)*, then coverage is complete.
    
    # For u prime, (Z/uZ)* is cyclic of order u-1.
    # A prime p generates a subgroup of order ord(p) | (u-1).
    # The divisor set mod u is contained in <p_1> × ... × <p_k> (with bounded exponents).
    
    # If k primes generate subgroups whose product (as subgroups) = (Z/uZ)*,
    # then the unbounded product set = (Z/uZ)*, and the bounded product set
    # is a subset that grows with the exponents.
    
    # For the bounded case (exponents 0..2e_i):
    # If e_i ≥ 1, then {0, 1, 2} ⊆ exponents, giving at least 3 elements per prime.
    # With k primes, |divisors| ≥ 3^k.
    # Pigeonhole: if 3^k ≥ u, then divisors might cover all of (Z/uZ)*.
    # But this is NOT sufficient (divisors can cluster).
    
    # The REAL condition: the bounded product set covers (Z/uZ)* when
    # the primes generate sufficiently independent subgroups.
    
    # For a LOWER BOUND on when coverage is guaranteed:
    # If ω(x) ≥ k and all e_i = 1 (worst case), then x² has exponents 0..2.
    # |divisors of x²| = 3^k.
    # Need 3^k ≥ u-1 for pigeonhole to even potentially work.
    
    pigeonhole_k = 1
    while 3**pigeonhole_k < u - 1:
        pigeonhole_k += 1
    
    return pigeonhole_k

