"""
Divisor Distribution Lemma: Prove that when ω(x) ≥ k, the u-method
is guaranteed to work for specific (u, k) pairs.

The key insight: divisors of x² mod u form a subset of (Z/uZ)*.
When this subset is large enough (relative to u), it MUST contain
one of the three targets.

This script computes the exact coverage for each (ω(x), u) pair
and determines the minimum ω(x) that guarantees success for each u.
"""

