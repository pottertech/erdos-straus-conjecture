def check_deterministic_coverage(u, omega, target_dlogs):
    """
    Check if for ALL possible choices of omega primes (i.e., all possible
    dlog combinations), the bounded subset sum covers at least one target.
    
    Since (Z/uZ)* is cyclic of order u-1, each prime's dlog is in Z/(u-1)Z.
    The divisor set is {sum(a_i * d_i) mod (u-1) : a_i ∈ {0,1,2}}.
    
    For deterministic coverage, we need: for ALL d_1, ..., d_omega in Z/(u-1)Z,
    the set {sum(a_i * d_i) : a_i ∈ {0,1,2}} intersects the target set.
    
    Equivalently: there is NO choice of d_1, ..., d_omega such that the
    bounded subset sum avoids ALL targets.
    """
    mod = u - 1  # (Z/uZ)* has order u-1
    
    # For small mod, we can check exhaustively over dlog combinations
    # But mod can be up to 126 (for u=127), and omega up to 5
    # 126^5 = 25 billion — too many for exhaustive
    
    # Instead, check the WORST CASE: all dlogs equal (most clustering)
    # If d_1 = d_2 = ... = d_omega = d, then:
    # subset sums = {a*d mod (u-1) : a ∈ {0, 1, ..., 2*omega}}
    # This is an arithmetic progression with 2*omega+1 terms.
    
    # For this to miss all targets, we need:
    # target_j ≢ a*d mod (u-1) for all a ∈ {0,...,2*omega} and all j
    
    # The AP {0, d, 2d, ..., 2*omega*d} has 2*omega+1 elements.
    # If gcd(d, u-1) = g, the AP is contained in g*Z/(u-1)Z (a coset).
    # For the AP to miss a target, the target must not be in this coset.
    
    # With 3 targets, we need ALL 3 to avoid the AP.
    # The AP has 2*omega+1 elements out of (u-1)/g coset elements.
    
    # For omega = 4, AP has 9 elements. If g = 1 (d coprime to u-1),
    # AP covers 9 out of u-1 = 126 residues. P(target in AP) = 9/126 = 7.1%.
    # P(all 3 targets miss) = (117/126)^3 = 80.8%. Not deterministic!
    
    # So the worst case (all dlogs equal) does NOT guarantee coverage.
    # The deterministic guarantee comes from DIVERSITY of dlogs.
    
    # The real argument: x = (n+u)/4 has SPECIFIC prime factors, not
    # adversarially chosen. The dlogs are determined by n and u.
    # The question is whether there EXISTS an n where all dlogs cluster.
    
    # This is the "all-QR" obstruction: if all primes of x are QR mod u,
    # their dlogs are all even, and the bounded sum stays in the even subgroup.
    # The target -1 has dlog (u-1)/2, which is odd for u ≡ 3 mod 4.
    # So the all-QR obstruction is the ONLY way the method fails.
    
    # For ω(x) = k, P(all QR) = (1/2)^k (each prime independently QR or QNR).
    # For k = 7: P = 1/128 < 1%
    # For k = 10: P = 1/1024 < 0.1%
    
    # But we need DETERMINISTIC, not probabilistic.
    # Deterministic requires: x has at least one QNR prime factor mod u.
    
    # GUARANTEE: If x has a prime factor p with (p/u) = -1 (QNR mod u),
    # then p's dlog is odd, and the bounded sum can reach odd dlogs,
    # potentially hitting the target.
    
    # But even with a QNR prime, the bounded sum might not reach the
    # SPECIFIC target value. The question is whether the QNR prime's
    # contribution is sufficient.
    
    # For u = 7, (Z/7Z)* has order 6. QR = {1,2,4} (dlogs 0,2,4), QNR = {3,5,6} (dlogs 1,3,5).
    # Target -1 = 6, dlog = 3. With one QNR prime p (dlog = d):
    # Bounded sums with exponents {0,1,2}: {0, d, 2d} mod 6.
    # If d = 1: {0, 1, 2} — misses 3.
    # If d = 3: {0, 3, 0} = {0, 3} — hits 3! ✓
    # If d = 5: {0, 5, 4} — misses 3.
    # So 1/3 of QNR primes hit the target for u=7 with ω=1.
    
    # With ω = 2 (one QR + one QNR): more combinations, higher hit rate.
    
    return None

