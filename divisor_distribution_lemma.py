from sympy import discrete_log

def min_omega_deterministic(u, max_omega=8):
    """
    For prime u, find the minimum ω such that for ALL possible
    dlog vectors (d_1, ..., d_ω) in Z/(u-1)Z, the bounded subset sum
    {sum(a_i * d_i) : a_i ∈ {0,1,2}} covers at least one of 3 targets.
    
    The 3 targets depend on n mod u. We check for ALL n mod u (coprime to u).
    """
    if not isprime(u):
        return None
    
    mod = u - 1  # group order
    
    # For each n mod u (coprime to u), compute target dlogs
    # Target T_a has dlog = dlog(-x * n^(1-a)) where x = n * inv(4) mod u
    # dlog(T_a) = dlog(-1) + dlog(x) + (1-a)*dlog(n) mod (u-1)
    # dlog(x) = dlog(n) + dlog(inv(4)) = dlog(n) - dlog(4) mod (u-1)
    # So dlog(T_a) = dlog(-1) + dlog(n) - dlog(4) + (1-a)*dlog(n)
    #             = dlog(-1) - dlog(4) + (2-a)*dlog(n) mod (u-1)
    
    g = primitive_root(u)
    
    dlog_neg1 = (mod // 2) % mod  # -1 = g^((u-1)/2) for u ≡ 3 mod 4
    dlog_4 = discrete_log(u, 4, g) if 4 % u != 0 else None
    if dlog_4 is None:
        return None
    dlog_inv4 = (-dlog_4) % mod
    
    # For each n mod u (coprime to u):
    # target dlogs = {dlog_neg1 + dlog_inv4 + (2-a)*dlog_n mod mod : a ∈ {0,1,2}}
    # = {c + 2*dlog_n, c + dlog_n, c : a = 0, 1, 2} where c = dlog_neg1 + dlog_inv4
    
    c = (dlog_neg1 + dlog_inv4) % mod
    
    # For each omega from 1 to max_omega:
    # Check if for ALL dlog vectors and ALL n mod u, the bounded sum hits a target
    
    for omega in range(1, max_omega + 1):
        all_covered = True
        
        # For each n mod u (coprime to u):
        for n_mod in range(1, u):
            if n_mod % u == 0:
                continue
            dlog_n = discrete_log(u, n_mod, g)
            targets_dlog = {(c + (2-a) * dlog_n) % mod for a in range(3)}
            
            # Check: for ALL d_1, ..., d_omega in Z/mod Z, 
            # {sum(a_i*d_i) : a_i ∈ {0,1,2}} ∩ targets_dlog ≠ ∅?
            #
            # This is equivalent to: there is NO dlog vector that avoids all targets.
            # 
            # For small mod, we can check by trying all d vectors.
            # mod^omega can be large, so we use sampling for large mod.
            
            if mod**omega <= 100000:
                # Exhaustive check
                def check_all_dlogs(omega, mod, targets):
                    """Check all dlog vectors of length omega."""
                    if omega == 0:
                        return 0 in targets
                    
                    for d_vec in itertools.product(range(mod), repeat=omega):
                        # Compute bounded subset sum
                        sums = {0}
                        for d in d_vec:
                            new_sums = set()
                            for s in sums:
                                new_sums.add(s)
                                new_sums.add((s + d) % mod)
                                new_sums.add((s + 2*d) % mod)
                            sums = new_sums
                        if sums & targets:
                            continue  # This dlog vector works
                        else:
                            return False  # Found a failing dlog vector!
                    return True  # All dlog vectors work
                
                if not check_all_dlogs(omega, mod, targets_dlog):
                    all_covered = False
                    break
            else:
                # Sampling (not deterministic, but indicative)
                # Skip for now — just note the limitation
                pass
        
        if all_covered:
            return omega
    
    return None

