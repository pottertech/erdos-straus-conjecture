#!/usr/bin/env python3
"""Generic exact centered verifier for arbitrary u.

For x=(n+u)/4 and M=n*x with gcd(M,u)=1, the u-method succeeds iff -1
belongs to the bounded centered product set generated by prime powers of M.

This implementation uses dynamic programming directly in (Z/uZ)^* rather than
assuming the unit group is cyclic.  For the small u used by the cascade this is
both simple and exact, and serves as a reference implementation for any later
coordinate/capacity optimizations.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import gcd
from sympy import factorint


@dataclass(frozen=True)
class CenteredResult:
    n: int
    u: int
    x: int
    M: int
    success: bool
    reachable_count: int
    phi_u: int
    factorization: dict[int, int]


def unit_group(u: int) -> set[int]:
    return {a for a in range(1, u) if gcd(a, u) == 1}


def centered_reachable(M: int, u: int) -> set[int]:
    """Return all residues reachable by bounded centered prime exponents."""
    if gcd(M, u) != 1:
        raise ValueError("centered criterion requires gcd(M,u)=1")

    reachable = {1 % u}
    for p, e in factorint(M).items():
        pmod = p % u
        pinv = pow(pmod, -1, u)

        local = {1}
        v = 1
        for _ in range(e):
            v = (v * pmod) % u
            local.add(v)

        v = 1
        for _ in range(e):
            v = (v * pinv) % u
            local.add(v)

        reachable = {(a * b) % u for a in reachable for b in local}

    return reachable


def centered_check(n: int, u: int) -> CenteredResult | None:
    if u <= 0 or (n + u) % 4 != 0:
        return None
    x = (n + u) // 4
    if x <= 0:
        return None
    M = n * x
    if gcd(M, u) != 1:
        return None

    reachable = centered_reachable(M, u)
    units = unit_group(u)
    if not reachable <= units:
        raise AssertionError("reachable set escaped unit group")

    return CenteredResult(
        n=n,
        u=u,
        x=x,
        M=M,
        success=((-1) % u) in reachable,
        reachable_count=len(reachable),
        phi_u=len(units),
        factorization=factorint(M),
    )


def subgroup_generated_by_factor_residues(M: int, u: int) -> set[int]:
    """Return subgroup generated by prime-factor residues of M modulo u."""
    if gcd(M, u) != 1:
        raise ValueError("requires gcd(M,u)=1")
    gens = {p % u for p in factorint(M)}
    H = {1 % u}
    changed = True
    while changed:
        changed = False
        snapshot = list(H)
        for h in snapshot:
            for g in gens:
                for z in ((h * g) % u, (h * pow(g, -1, u)) % u):
                    if z not in H:
                        H.add(z)
                        changed = True
    return H


def failure_fingerprint(n: int, u: int) -> dict | None:
    """Classify an exact failure as subgroup-pure or capacity-exceptional."""
    result = centered_check(n, u)
    if result is None:
        return None
    H = subgroup_generated_by_factor_residues(result.M, u)
    minus_one_in_generated_subgroup = ((-1) % u) in H

    return {
        "n": n,
        "u": u,
        "x": result.x,
        "M": result.M,
        "success": result.success,
        "reachable_count": result.reachable_count,
        "phi_u": result.phi_u,
        "generated_subgroup_size": len(H),
        "minus_one_in_generated_subgroup": minus_one_in_generated_subgroup,
        "failure_type": (
            None if result.success else
            "capacity_exception" if minus_one_in_generated_subgroup else
            "subgroup_pure"
        ),
        "factorization": result.factorization,
    }


def self_test() -> None:
    # Known exact failure at u=7 followed by success at u=11.
    a = failure_fingerprint(1129, 7)
    assert a and not a["success"]
    b = failure_fingerprint(1129, 11)
    assert b and b["success"]

    # Known final 10^7 outlier succeeds at u=107.
    c = failure_fingerprint(8_803_369, 107)
    assert c and c["success"]

    print("self-test passed")


if __name__ == "__main__":
    self_test()
