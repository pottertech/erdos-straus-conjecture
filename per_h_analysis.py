#!/usr/bin/env python3
"""
Per-h Finite Case Analysis (Problem #7)
========================================
For each h ∈ {6, 10, 18, 22, 30}, analyze the trivial-stabilizer gap cases
and prove the parity obstruction cannot persist across all 6 group orders.

Key facts from v9:
- The covering set primes {3, 7, 11, 19, 23, 31} produce group orders h ∈ {2, 6, 10, 18, 22, 30}
- For h=2 (A=3): no gaps (Theorem 2 covers n ≡ 5 mod 8; n ≡ 1 mod 8 has (3/n)=1 so A=3 doesn't apply)
- For each h > 2, the parity obstruction puts dlog(T) at an odd position
- Different A values give different h, so the obstruction in one Z/hZ doesn't propagate

Strategy:
1. For each h, enumerate all gap cases (n, A) with that h
2. For each gap case, determine which OTHER A' in the covering set rescues it
3. Prove: for each n with a gap at h, at least one A' gives h' where the parity obstruction vanishes
4. Formalize: the parity obstruction requires h/2 odd AND dlog(nm) even AND the specific odd position is a hole
   Different h' changes all three conditions.
"""

import json
import sympy
from sympy import isprime, prevprime, nextprime, factorint, gcd, mod_inverse
from collections import defaultdict, Counter
from itertools import product as iterproduct

# Covering set
COVERING_A = [3, 7, 11, 15, 19, 23, 27, 31]
PRIME_A = [3, 7, 11, 19, 23, 31]  # composite A removed

def compute_h_and_dlog(n, A):
    """
    For given n (prime, n ≡ 1 mod 12, n ≢ 0 mod 5) and A (≡ 3 mod 4, gcd(n,A)=1),
    compute:
    - h = |H(A)| = order of subgroup generated by prime factors of nx mod A
    - dlog(T) = h/2 + dlog(nm) mod h  (the target's discrete log position)
    - dlog(nm) = sum of e_i * s_i mod h
    - Whether T ∈ D_A (gap or not)
    - The parity of dlog(T)
    - Which odd positions are holes in D_A
    
    Returns dict with all info, or None if gcd(n,A) > 1
    """
    if gcd(n, A) > 1:
        return None
    
    m = (n + A) // 4
    nx = n * m
    
    # Prime factors of nx coprime to A
    factors = factorint(nx)
    prime_factors = []
    for p, e in factors.items():
        if gcd(p, A) == 1:
            prime_factors.append((p, e))
    
    if not prime_factors:
        return None
    
    # Find primitive root mod A (A prime case)
    if not isprime(A):
        # For composite A, use the group (Z/AZ)* which may not be cyclic
        # Fall back to computing H(A) directly
        return compute_h_composite_A(n, A, m, nx, prime_factors)
    
    # Find primitive root g mod A
    g = find_primitive_root(A)
    if g is None:
        return None
    
    # Compute dlog of each prime factor mod A
    # dlog_g(p) = discrete log of p base g mod A
    dlogs = {}
    for p, e in prime_factors:
        dlogs[p] = discrete_log_mod(g, p, A)
    
    # h = order of subgroup H(A) generated by prime factors
    # H(A) = <g^{(A-1)/h}> where h = |H(A)|
    # Actually, h = lcm of orders of generators
    orders = []
    for p, e in prime_factors:
        ord_p = multiplicative_order(p, A)
        orders.append(ord_p)
    
    from math import lcm
    h = 1
    for o in orders:
        h = lcm(h, o)
    
    # dlog of each prime in Z/hZ: s_i = dlog_g(p_i) * (A-1)/h mod h
    # Actually, we work in the subgroup H(A) = <g^((A-1)/h)>
    # The dlog within H(A) is dlog_g(p_i) / ((A-1)/h) mod h
    # But it's easier to work directly: s_i = dlog_g(p_i) mod h (using the quotient)
    
    # Let me use a cleaner approach:
    # Work in Z/hZ where the generator is g^((A-1)/h)
    # dlog of p_i in Z/hZ = dlog_g(p_i) / ((A-1)/h) mod h
    
    s_values = {}
    for p, e in prime_factors:
        # dlog of p base g mod A
        dlg = discrete_log_mod(g, p, A)
        # Convert to dlog in Z/hZ: divide by (A-1)/h
        step = (A - 1) // h
        # s_i = dlg / step mod h
        if h <= 1:
            s_values[p] = 0
            continue
        try:
            s_inv = mod_inverse(step, h)
            s_i = (dlg * s_inv) % h
        except (ValueError, Exception):
            # step and h not coprime; find s such that s*step ≡ dlg (mod h)
            s_i = None
            for s in range(h):
                if (s * step) % h == dlg % h:
                    s_i = s
                    break
            if s_i is None:
                return None
        s_values[p] = s_i
    
    # dlog(nm) = sum of e_i * s_i mod h
    dlog_nm = 0
    for p, e in prime_factors:
        dlog_nm = (dlog_nm + e * s_values[p]) % h
    
    # dlog(T) = h/2 + dlog(nm) mod h
    dlog_T = (h // 2 + dlog_nm) % h
    
    # Compute D_A as the bounded sumset in Z/hZ
    # D_A = { sum of a_i * s_i mod h : 0 <= a_i <= 2*e_i }
    D_A_elements = set()
    ranges = [range(2 * e + 1) for _, e in prime_factors]
    s_list = [s_values[p] for p, _ in prime_factors]
    
    for combo in iterproduct(*ranges):
        val = 0
        for a_i, s_i in zip(combo, s_list):
            val = (val + a_i * s_i) % h
        D_A_elements.add(val)
    
    # Is T in D_A?
    T_in_D = dlog_T in D_A_elements
    
    # Stabilizer of D_A in Z/hZ
    stab = set()
    for s in range(h):
        if all((d + s) % h in D_A_elements for d in D_A_elements):
            stab.add(s)
    
    # -1 in D_A? (dlog of -1 is h/2)
    neg1_in_D = (h // 2) in D_A_elements
    
    # Parity of dlog(T)
    parity_T = dlog_T % 2
    
    # Which odd positions are holes?
    all_positions = set(range(h))
    holes = all_positions - D_A_elements
    odd_holes = {d for d in holes if d % 2 == 1}
    even_holes = {d for d in holes if d % 2 == 0}
    
    return {
        'n': n,
        'A': A,
        'h': h,
        'm': m,
        'dlog_T': dlog_T,
        'dlog_nm': dlog_nm,
        'parity_T': parity_T,
        'T_in_D': T_in_D,
        'neg1_in_D': neg1_in_D,
        'stab_size': len(stab),
        'stab': sorted(stab),
        'D_A_size': len(D_A_elements),
        'D_A': sorted(D_A_elements),
        'holes': sorted(holes),
        'odd_holes': sorted(odd_holes),
        'even_holes': sorted(even_holes),
        'prime_factors': [(p, e) for p, e in prime_factors],
        's_values': {p: s_values[p] for p, _ in prime_factors},
    }


def compute_h_composite_A(n, A, m, nx, prime_factors):
    """Handle composite A case - (Z/AZ)* may not be cyclic."""
    # For composite A, we work in (Z/AZ)* directly
    # H(A) = subgroup generated by prime factors of nx mod A
    
    # Generate H(A) by multiplying generators
    H = set([1])
    for p, e in prime_factors:
        p_mod = p % A
        new_H = set()
        for h_elem in H:
            for exp in range(e + 1):  # up to e powers (for subgroup membership)
                new_H.add(pow(p_mod, exp, A) * h_elem % A)
        H = new_H
    
    # Actually, H(A) is the subgroup, so we need closure
    # Generate full subgroup
    changed = True
    while changed:
        changed = False
        new_H = set(H)
        for p, _ in prime_factors:
            p_mod = p % A
            for h_elem in list(H):
                val = (p_mod * h_elem) % A
                if val not in new_H:
                    new_H.add(val)
                    changed = True
        H = new_H
    
    h = len(H)
    
    # For composite A, -1 has order 2 in (Z/AZ)*
    # Check if -1 mod A is in H
    neg1 = (-1) % A
    neg1_in_H = neg1 in H
    
    # Check if -1 in D_A (bounded divisor set)
    D_A_set = set([1])
    for p, e in prime_factors:
        p_mod = p % A
        new_D = set()
        for d_elem in D_A_set:
            for exp in range(2 * e + 1):
                new_D.add(pow(p_mod, exp, A) * d_elem % A)
        D_A_set = new_D
    
    neg1_in_D = neg1 in D_A_set
    
    # Target T = -n^2 * 4^{-1} mod A
    T = (-n * n * mod_inverse(4, A)) % A
    T_in_D = T in D_A_set
    
    # For composite A, we can't easily compute dlog since the group isn't cyclic
    # Return what we can
    return {
        'n': n,
        'A': A,
        'h': h,
        'm': m,
        'dlog_T': None,  # Not well-defined for non-cyclic group
        'dlog_nm': None,
        'parity_T': None,
        'T_in_D': T_in_D,
        'neg1_in_D': neg1_in_D,
        'stab_size': None,  # Would need more work
        'stab': None,
        'D_A_size': len(D_A_set),
        'D_A': sorted(D_A_set),
        'holes': None,
        'odd_holes': None,
        'even_holes': None,
        'prime_factors': [(p, e) for p, e in prime_factors],
        's_values': None,
        'composite_A': True,
    }


def find_primitive_root(p):
    """Find a primitive root modulo prime p."""
    if p == 2:
        return 1
    phi = p - 1
    factors = factorint(phi)
    for g in range(2, p):
        is_primitive = True
        for q in factors:
            if pow(g, phi // q, p) == 1:
                is_primitive = False
                break
        if is_primitive:
            return g
    return None


def discrete_log_mod(g, target, p):
    """Compute discrete log of target base g mod p. Brute force for small p."""
    if target % p == 0:
        return None
    val = 1
    for i in range(p - 1):
        if val == target % p:
            return i
        val = (val * g) % p
    return None


def multiplicative_order(a, n):
    """Compute multiplicative order of a mod n."""
    if gcd(a, n) > 1:
        return None
    val = a % n
    for i in range(1, n):
        if val == 1:
            return i
        val = (val * a) % n
    return None


def scan_all_cases(max_n=100000):
    """
    Scan all prime n ≤ max_n with n ≡ 1 (mod 12), n ≢ 0 (mod 5).
    For each, compute D_A for each A in covering set.
    Identify gap cases and categorize by h.
    """
    results = []
    gap_cases = []
    
    n = 13  # first prime ≡ 1 mod 12
    while n <= max_n:
        if n % 12 == 1 and n % 5 != 0 and isprime(n):
            for A in COVERING_A:
                if gcd(n, A) > 1:
                    continue
                info = compute_h_and_dlog(n, A)
                if info is None:
                    continue
                info['is_gap'] = not info['T_in_D']
                results.append(info)
                if not info['T_in_D']:
                    gap_cases.append(info)
        n = nextprime(n)
    
    return results, gap_cases


def analyze_per_h(gap_cases):
    """
    For each h value, analyze the gap cases:
    - How many gaps
    - Parity structure
    - Which A' rescues each gap
    - Why the obstruction can't persist across all h
    """
    # Group by h
    by_h = defaultdict(list)
    for case in gap_cases:
        if case.get('composite_A'):
            continue  # Skip composite A for dlog analysis
        by_h[case['h']].append(case)
    
    print("=" * 80)
    print("PER-H FINITE CASE ANALYSIS (Problem #7)")
    print("=" * 80)
    
    # For each h, show the gap structure
    for h in sorted(by_h.keys()):
        cases = by_h[h]
        print(f"\n{'='*60}")
        print(f"h = {h} (A values: {sorted(set(c['A'] for c in cases))})")
        print(f"Gap cases: {len(cases)}")
        print(f"{'='*60}")
        
        # Parity analysis
        parity_counts = Counter(c['parity_T'] for c in cases)
        print(f"  dlog(T) parity: {dict(parity_counts)}")
        print(f"  h/2 = {h//2} ({'odd' if (h//2) % 2 == 1 else 'even'})")
        
        # All dlog(T) values
        dlog_T_values = Counter(c['dlog_T'] for c in cases)
        print(f"  dlog(T) distribution: {dict(sorted(dlog_T_values.items()))}")
        
        # Hole structure
        all_odd_holes = set()
        for c in cases:
            if c.get('odd_holes'):
                all_odd_holes.update(c['odd_holes'])
        print(f"  Union of odd holes across all cases: {sorted(all_odd_holes)}")
        
        # Stabilizer sizes
        stab_counts = Counter(c['stab_size'] for c in cases)
        print(f"  Stabilizer sizes: {dict(stab_counts)}")
        
        # For each gap case, find rescuing A'
        rescue_by_A = defaultdict(int)
        rescue_by_h = defaultdict(int)
        no_rescue = 0
        
        for case in cases:
            n = case['n']
            rescued = False
            for A2 in COVERING_A:
                if A2 == case['A']:
                    continue
                if gcd(n, A2) > 1:
                    continue
                info2 = compute_h_and_dlog(n, A2)
                if info2 and info2['T_in_D']:
                    rescued = True
                    rescue_by_A[A2] += 1
                    if info2.get('h'):
                        rescue_by_h[info2['h']] += 1
            if not rescued:
                no_rescue += 1
        
        print(f"  Rescue A distribution: {dict(sorted(rescue_by_A.items()))}")
        print(f"  Rescue h distribution: {dict(sorted(rescue_by_h.items()))}")
        print(f"  No rescue (should be 0): {no_rescue}")
    
    # Cross-h analysis: for each n, which h values produce gaps?
    print(f"\n{'='*60}")
    print("CROSS-H ANALYSIS: Per-n gap patterns")
    print(f"{'='*60}")
    
    n_gaps = defaultdict(list)  # n -> list of (h, A) that gap
    for case in gap_cases:
        if case.get('composite_A'):
            continue
        n_gaps[case['n']].append((case['h'], case['A']))
    
    # How many h values gap for each n?
    h_count_per_n = Counter(len(v) for v in n_gaps.values())
    print(f"  Number of h-values that gap per n: {dict(h_count_per_n)}")
    
    # Which combinations of h values gap together?
    h_combos = Counter()
    for n, hA_list in n_gaps.items():
        h_set = tuple(sorted(set(h for h, A in hA_list)))
        h_combos[h_set] += 1
    print(f"  h-value gap combinations (h_set: count):")
    for hset, cnt in sorted(h_combos.items(), key=lambda x: -x[1]):
        print(f"    {hset}: {cnt}")
    
    # Key question: does any n have gaps at ALL h values?
    all_h_values = {2, 6, 10, 18, 22, 30}
    n_with_all_h_gap = 0
    for n, hA_list in n_gaps.items():
        h_set = set(h for h, A in hA_list)
        if h_set == all_h_values:
            n_with_all_h_gap += 1
    print(f"  n with gaps at ALL h values: {n_with_all_h_gap}")
    
    # Maximum number of h values that gap for any single n
    max_h_gap = max(len(set(h for h, A in hA_list)) for hA_list in n_gaps.values()) if n_gaps else 0
    print(f"  Max h-values that gap for any single n: {max_h_gap}")
    
    return by_h, n_gaps


def parity_obstruction_formal_analysis(by_h, n_gaps):
    """
    Formal analysis of why the parity obstruction can't persist across all h.
    
    The parity obstruction at h requires:
    1. h/2 is odd (h ≡ 2 mod 4)
    2. dlog(nm) is even
    3. The specific odd position h/2 + dlog(nm) is a hole in D_A
    
    For the obstruction to persist at h', we need the SAME conditions at h'.
    Key insight: dlog(nm) mod h' has different parity structure because:
    - The generators s_i are different (different A, different primitive root)
    - The exponents e_i are the same but weighted differently
    - h'/2 has different parity
    
    We need to show: for any n, at least one h avoids the obstruction.
    """
    print(f"\n{'='*80}")
    print("PARITY OBSTRUCTION FORMAL ANALYSIS")
    print(f"{'='*80}")
    
    # For each h, what are the conditions?
    print("\nCondition 1: h/2 must be odd (h ≡ 2 mod 4)")
    for h in sorted(by_h.keys()):
        half = h // 2
        print(f"  h={h}: h/2={half}, odd={half % 2 == 1}")
    
    print("\nCondition 2: dlog(nm) must be even")
    for h in sorted(by_h.keys()):
        cases = by_h[h]
        dlog_nm_parities = Counter(c['dlog_nm'] % 2 for c in cases)
        print(f"  h={h}: dlog(nm) parity {dict(dlog_nm_parities)}")
    
    print("\nCondition 3: The odd position h/2 + dlog(nm) must be a hole")
    for h in sorted(by_h.keys()):
        cases = by_h[h]
        # All gap cases have T at odd positions that are holes
        hole_positions = Counter(c['dlog_T'] for c in cases)
        print(f"  h={h}: T positions that gap: {dict(sorted(hole_positions.items()))}")
    
    # Critical: show that for each n with gaps, the rescue h' breaks at least one condition
    print(f"\n{'='*60}")
    print("RESCUE ANALYSIS: Which condition breaks at the rescue h'?")
    print(f"{'='*60}")
    
    condition_breaks = {'h/2_even': 0, 'dlog_nm_odd': 0, 'T_not_hole': 0, 'multiple': 0}
    
    for n, hA_list in n_gaps.items():
        gap_h_set = set(h for h, A in hA_list)
        
        # Find the rescue h'
        for A2 in COVERING_A:
            if gcd(n, A2) > 1:
                continue
            info2 = compute_h_and_dlog(n, A2)
            if info2 is None or not info2['T_in_D']:
                continue
            
            h2 = info2['h']
            if h2 in gap_h_set:
                continue  # This h also gaps, not a rescue
            
            # Which conditions break?
            breaks = []
            
            # Condition 1: h2/2 even?
            if (h2 // 2) % 2 == 0:
                breaks.append('h/2_even')
            
            # Condition 2: dlog(nm) odd at h2?
            if info2.get('dlog_nm') is not None and info2['dlog_nm'] % 2 == 1:
                breaks.append('dlog_nm_odd')
            
            # Condition 3: T position not a hole (i.e., T ∈ D_A)
            breaks.append('T_not_hole')  # Always true since T_in_D
            
            if len(breaks) > 1:
                condition_breaks['multiple'] += 1
            elif breaks:
                condition_breaks[breaks[0]] += 1
            break  # Found the rescue
    
    print(f"  Condition breaks at rescue h': {condition_breaks}")
    
    # The key theorem we want to prove:
    # For each n, the set of h values where the parity obstruction holds is a PROPER subset
    # of {6, 10, 18, 22, 30} (and h=2 never has the obstruction).
    # Therefore at least one h' avoids it.
    
    print(f"\n{'='*60}")
    print("THEOREM STATEMENT (to prove):")
    print(f"{'='*60}")
    max_h_gap = max(len(set(h for h, A in hA_list)) for hA_list in n_gaps.values()) if n_gaps else 0
    print(f"""
    For any prime n ≡ 1 (mod 12), n ≢ 0 (mod 5):
    Let H_gap(n) = {{ h ∈ {{6, 10, 18, 22, 30}} : ∃ A with ord_A-structure giving h,
                     and T ∉ D_A((nx)²) }}.
    
    Then H_gap(n) ≠ {{6, 10, 18, 22, 30}} for any n.
    (I.e., not all h values can simultaneously produce gaps.)
    
    Computational verification: max |H_gap(n)| = {max_h_gap}
    among all n ≤ 100,000.
    """)


def main():
    print("Scanning all cases up to n = 100,000...")
    results, gap_cases = scan_all_cases(100000)
